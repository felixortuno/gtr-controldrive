CREATE TABLE nucleo.documentos (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo           text NOT NULL,
  titular        text NOT NULL,
  conductor_id   bigint REFERENCES nucleo.conductores,
  vehiculo_id    bigint REFERENCES nucleo.vehiculos,
  remolque_id    bigint REFERENCES nucleo.remolques,
  caduca_el      date NOT NULL,
  archivo_id     bigint REFERENCES nucleo.archivos,
  apto           boolean,
  estado         text NOT NULL DEFAULT 'pendiente_validacion' CHECK (estado IN ('pendiente_validacion', 'vigente', 'sustituido', 'rechazado')),
  subido_por     bigint REFERENCES nucleo.usuarios,
  validado_por   bigint REFERENCES nucleo.usuarios,
  validado_en    timestamptz,
  creado_en      timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (tipo, titular) REFERENCES nucleo.tipos_documento (codigo, titular),
  CHECK (
       (titular = 'conductor' AND conductor_id IS NOT NULL AND vehiculo_id IS NULL AND remolque_id IS NULL)
    OR (titular = 'vehiculo'  AND vehiculo_id  IS NOT NULL AND conductor_id IS NULL AND remolque_id IS NULL)
    OR (titular = 'remolque'  AND remolque_id  IS NOT NULL AND conductor_id IS NULL AND vehiculo_id IS NULL)),
  CHECK (apto IS NULL OR tipo = 'revision_medica'),
  CHECK (estado <> 'vigente' OR validado_por IS NOT NULL)
);
CREATE UNIQUE INDEX documentos_uno_vigente ON nucleo.documentos
  (tipo, coalesce(conductor_id, 0), coalesce(vehiculo_id, 0), coalesce(remolque_id, 0))
  WHERE estado = 'vigente';
CREATE INDEX documentos_caducidad ON nucleo.documentos (caduca_el) WHERE estado = 'vigente';
CREATE TRIGGER documentos_actualizado BEFORE UPDATE ON nucleo.documentos FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.documentos IS 'Cada documento con su fecha de caducidad. Un solo documento vigente por titular y tipo; al validar uno nuevo, el anterior pasa a «sustituido» y los avisos se paran solos.';
COMMENT ON COLUMN nucleo.documentos.titular IS 'De quién es: conductor, vehiculo o remolque. Debe coincidir con el tipo y con la columna rellena (lo garantizan las restricciones).';
COMMENT ON COLUMN nucleo.documentos.apto IS 'Solo revisión médica. Sin datos médicos: los informes se quedan en el servicio de prevención.';
COMMENT ON COLUMN nucleo.documentos.estado IS 'El chófer sube la foto (pendiente_validacion), tráfico la valida (vigente).';

CREATE TABLE nucleo.reglas_aviso (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  frase              text NOT NULL,
  tipo_documento     text NOT NULL REFERENCES nucleo.tipos_documento,
  conductor_id       bigint REFERENCES nucleo.conductores,
  vehiculo_id        bigint REFERENCES nucleo.vehiculos,
  remolque_id        bigint REFERENCES nucleo.remolques,
  dias_antes         integer NOT NULL CHECK (dias_antes BETWEEN 0 AND 365),
  destinatarios      text[] NOT NULL,
  canales            text[] NOT NULL CHECK (canales <@ ARRAY['app', 'email', 'whatsapp'] AND cardinality(canales) > 0),
  repetir_cada_dias  integer CHECK (repetir_cada_dias > 0),
  activa             boolean NOT NULL DEFAULT true,
  creada_por         bigint REFERENCES nucleo.usuarios,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(conductor_id, vehiculo_id, remolque_id) <= 1)
);
COMMENT ON TABLE nucleo.reglas_aviso IS 'Avisos de caducidad programados «rellenando una frase». Sin titular concreto, la regla vale para todos los documentos de ese tipo.';
COMMENT ON COLUMN nucleo.reglas_aviso.frase IS 'La frase tal como la ve tráfico: «Avisar 30 días antes de que caduque la ITV del remolque a tráfico y al taller por app y email, cada semana hasta que se renueve».';
COMMENT ON COLUMN nucleo.reglas_aviso.destinatarios IS 'Roles (admin, trafico, taller…) o «titular» para el propio chófer.';
COMMENT ON COLUMN nucleo.reglas_aviso.repetir_cada_dias IS 'Vacío = un solo aviso. 7 = cada semana hasta que se renueve.';

INSERT INTO nucleo.reglas_aviso (frase, tipo_documento, dias_antes, destinatarios, canales)
SELECT format('Avisar %s días antes de que caduque %s', d, t.nombre),
       t.codigo, d,
       CASE WHEN t.titular = 'conductor' THEN ARRAY['titular', 'admin'] ELSE ARRAY['admin'] END,
       ARRAY['app']
FROM nucleo.tipos_documento t
CROSS JOIN (VALUES (60), (30), (7)) AS dias(d);


-- Notificaciones (todas las fases las usan) ------------------------------

CREATE TABLE sistema.notificaciones (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id       bigint NOT NULL REFERENCES nucleo.usuarios,
  canal            text NOT NULL CHECK (canal IN ('app', 'push', 'email', 'whatsapp')),
  titulo           text NOT NULL,
  cuerpo           text,
  enlace           text,
  origen           text NOT NULL CHECK (origen IN ('regla_aviso', 'aviso_correccion', 'mensaje', 'ausencia', 'tarea', 'canje', 'sistema')),
  origen_id        bigint,
  clave_unica      text UNIQUE,
  programada_para  timestamptz NOT NULL DEFAULT now(),
  enviada_en       timestamptz,
  leida_en         timestamptz,
  intentos         smallint NOT NULL DEFAULT 0,
  error            text,
  creado_en        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notificaciones_por_enviar ON sistema.notificaciones (programada_para) WHERE enviada_en IS NULL;
CREATE INDEX notificaciones_usuario ON sistema.notificaciones (usuario_id, creado_en DESC);
COMMENT ON TABLE sistema.notificaciones IS 'Cola de salida: todo aviso (app, push, email, WhatsApp) se escribe aquí y una tarea lo envía. Si un envío falla, se reintenta sin perder nada.';
COMMENT ON COLUMN sistema.notificaciones.clave_unica IS 'Evita duplicados si la tarea corre dos veces: «regla:12|doc:345|2026-11-02|u7|email».';


-- Mensajes ---------------------------------------------------------------

CREATE TABLE nucleo.conversaciones (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo               text NOT NULL CHECK (tipo IN ('conductor', 'grupo', 'flota')),
  titulo             text,
  conductor_id       bigint REFERENCES nucleo.conductores,
  creada_por         bigint REFERENCES nucleo.usuarios,
  creada_en          timestamptz NOT NULL DEFAULT now(),
  ultimo_mensaje_en  timestamptz,
  CHECK ((tipo = 'conductor') = (conductor_id IS NOT NULL))
);
CREATE UNIQUE INDEX conversaciones_una_por_conductor ON nucleo.conversaciones (conductor_id) WHERE tipo = 'conductor';
COMMENT ON TABLE nucleo.conversaciones IS 'Hilos de mensajes. Cada chófer tiene uno con la oficina; además puede haber grupos y avisos a toda la flota.';

CREATE TABLE nucleo.participantes (
  conversacion_id  bigint NOT NULL REFERENCES nucleo.conversaciones,
  usuario_id       bigint NOT NULL REFERENCES nucleo.usuarios,
  leido_hasta      timestamptz,
  silenciada       boolean NOT NULL DEFAULT false,
  PRIMARY KEY (conversacion_id, usuario_id)
);
COMMENT ON TABLE nucleo.participantes IS 'Quién está en cada conversación y hasta dónde ha leído.';
COMMENT ON COLUMN nucleo.participantes.leido_hasta IS 'Un mensaje está leído por alguien si su enviado_en es anterior o igual a este valor.';

CREATE TABLE nucleo.mensajes (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversacion_id  bigint NOT NULL REFERENCES nucleo.conversaciones,
  autor_id         bigint NOT NULL REFERENCES nucleo.usuarios,
  texto            text,
  foto_id          bigint REFERENCES nucleo.archivos,
  enviado_en       timestamptz NOT NULL DEFAULT now(),
  borrado_en       timestamptz,
  CHECK (texto IS NOT NULL OR foto_id IS NOT NULL)
);
CREATE INDEX mensajes_conversacion ON nucleo.mensajes (conversacion_id, enviado_en);
COMMENT ON TABLE nucleo.mensajes IS 'Cada mensaje, con texto o foto. Con el camión en marcha el chófer solo recibe el aviso (regla de la app).';

CREATE VIEW calculo.mensajes_lectura AS
SELECT m.id AS mensaje_id,
       m.conversacion_id,
       count(p.usuario_id) FILTER (WHERE p.usuario_id <> m.autor_id) AS destinatarios,
       count(p.usuario_id) FILTER (WHERE p.usuario_id <> m.autor_id AND p.leido_hasta >= m.enviado_en) AS leido_por
FROM nucleo.mensajes m
JOIN nucleo.participantes p ON p.conversacion_id = m.conversacion_id
WHERE m.borrado_en IS NULL
GROUP BY m.id, m.conversacion_id;
COMMENT ON VIEW calculo.mensajes_lectura IS 'Confirmación de lectura de cada mensaje: a cuántos les llegó y cuántos lo han leído.';

CREATE VIEW calculo.semaforo_documentos AS
SELECT d.id AS documento_id,
       d.tipo,
       d.titular,
       coalesce(d.conductor_id, d.vehiculo_id, d.remolque_id) AS titular_id,
       d.caduca_el,
       d.caduca_el - current_date AS dias_restantes,
       CASE
         WHEN d.caduca_el < current_date THEN 'rojo'
         WHEN d.caduca_el - current_date <= (sistema.parametro('documentos.ambar_dias'))::int THEN 'ambar'
         ELSE 'verde'
       END AS semaforo
FROM nucleo.documentos d
WHERE d.estado = 'vigente';
COMMENT ON VIEW calculo.semaforo_documentos IS 'Semáforo de caducidades: verde al día, ámbar a menos de 60 días (parámetro), rojo caducado.';
