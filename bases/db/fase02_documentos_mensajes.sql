-- Documentación ----------------------------------------------------------

CREATE TABLE nucleo.tipos_documento (
  codigo          text PRIMARY KEY,
  nombre          text NOT NULL,
  titular         text NOT NULL CHECK (titular IN ('conductor', 'vehiculo', 'remolque')),
  renovacion      text NOT NULL,
  requiere_apto   boolean NOT NULL DEFAULT false,
  UNIQUE (codigo, titular)
);
COMMENT ON TABLE nucleo.tipos_documento IS 'Qué documentos se controlan y de quién son. Añadir uno nuevo (p. ej. CAP) es un INSERT.';
COMMENT ON COLUMN nucleo.tipos_documento.renovacion IS 'Cada cuánto se renueva, en palabras: «Cada 5 años».';
COMMENT ON COLUMN nucleo.tipos_documento.requiere_apto IS 'Solo la revisión médica: se guarda si es apto, nunca diagnósticos.';

