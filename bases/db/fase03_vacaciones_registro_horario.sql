-- Registro horario ---------------------------------------------------------

CREATE TABLE nucleo.jornadas (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id        bigint NOT NULL REFERENCES nucleo.conductores,
  entrada             timestamptz NOT NULL,
  salida              timestamptz,
  origen_entrada      text NOT NULL CHECK (origen_entrada IN ('app', 'tacografo', 'admin')),
  origen_salida       text CHECK (origen_salida IN ('app', 'tacografo', 'admin', 'cierre_auto')),
  corregida_por       bigint REFERENCES nucleo.usuarios,
  motivo_correccion   text,
  odoo_asistencia_id  integer UNIQUE,
  copiada_odoo_en     timestamptz,
  creado_en           timestamptz NOT NULL DEFAULT now(),
  actualizado_en      timestamptz NOT NULL DEFAULT now(),
  CHECK (salida IS NULL OR salida > entrada),
  CHECK ((salida IS NULL) = (origen_salida IS NULL)),
  CHECK ('admin' NOT IN (origen_entrada, coalesce(origen_salida, '')) OR (corregida_por IS NOT NULL AND motivo_correccion IS NOT NULL)),
  CONSTRAINT jornadas_sin_solape EXCLUDE USING gist (conductor_id WITH =, tstzrange(entrada, salida) WITH &&)
);
CREATE UNIQUE INDEX jornadas_una_abierta ON nucleo.jornadas (conductor_id) WHERE salida IS NULL;
CREATE INDEX jornadas_por_copiar ON nucleo.jornadas (id) WHERE copiada_odoo_en IS NULL;
CREATE TRIGGER jornadas_actualizado BEFORE UPDATE ON nucleo.jornadas FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.jornadas IS 'Registro horario: entrada y salida de cada jornada. Nace en la app (empezar y terminar la jornada) y se copia a Asistencias de Odoo. Se guarda 4 años.';
COMMENT ON COLUMN nucleo.jornadas.origen_entrada IS 'app (botón del chófer), tacografo (metió la tarjeta sin abrir la app) o admin (corrección en el panel, con motivo).';
COMMENT ON COLUMN nucleo.jornadas.origen_salida IS 'Igual que la entrada, más cierre_auto: el camión lleva horas parado y nadie cerró la jornada. Queda para que tráfico la revise.';
COMMENT ON COLUMN nucleo.jornadas.odoo_asistencia_id IS 'Id de la asistencia en Odoo una vez copiada.';
COMMENT ON COLUMN nucleo.jornadas.copiada_odoo_en IS 'Cuándo se copió a Odoo. Vacía = pendiente: una tarea la reintenta. Si se corrige, se vacía y se vuelve a enviar.';
COMMENT ON CONSTRAINT jornadas_sin_solape ON nucleo.jornadas IS 'Un chófer no puede tener dos jornadas que se pisen: la base de datos lo rechaza.';

CREATE TABLE nucleo.asistencias_odoo (
  odoo_asistencia_id  integer PRIMARY KEY,
  conductor_id        bigint NOT NULL REFERENCES nucleo.conductores,
  entrada             timestamptz NOT NULL,
  salida              timestamptz,
  jornada_id          bigint REFERENCES nucleo.jornadas,
  cambiada_en_odoo    timestamptz,
  lote_id             bigint REFERENCES ingesta.lotes,
  sincronizado_en     timestamptz NOT NULL DEFAULT now(),
  CHECK (salida IS NULL OR salida > entrada)
);
CREATE INDEX asistencias_odoo_conductor ON nucleo.asistencias_odoo (conductor_id, entrada);
COMMENT ON TABLE nucleo.asistencias_odoo IS 'Asistencias de Odoo tal como están allí: son las horas que se pagan. Se traen cada hora, también las que RRHH cambia o mete a mano en Odoo. Las horas pagadas del panel salen de aquí, no de nucleo.jornadas.';
COMMENT ON COLUMN nucleo.asistencias_odoo.jornada_id IS 'La jornada de la app de la que salió. Vacía = la metió alguien directamente en Odoo.';
COMMENT ON COLUMN nucleo.asistencias_odoo.cambiada_en_odoo IS 'Última modificación en Odoo. Si es posterior a la copia desde la app, alguien la cambió allí y el panel lo enseña.';


