COMMENT ON COLUMN nucleo.saldos_vacaciones.al_final_del_anio_dias IS 'Los que tendrá generados el 31 de diciembre si sigue trabajando: «a final de año tendrás 30».';


-- Lo que se deduce ---------------------------------------------------------

CREATE VIEW calculo.horas_pagadas_dia AS
SELECT a.conductor_id,
       (a.entrada AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::date AS fecha,
       min(a.entrada) AS primera_entrada,
       max(a.salida) AS ultima_salida,
       bool_or(a.salida IS NULL) AS abierta,
       round(sum(extract(epoch FROM coalesce(a.salida, now()) - a.entrada)) / 3600, 2) AS horas
FROM nucleo.asistencias_odoo a
GROUP BY 1, 2;
COMMENT ON VIEW calculo.horas_pagadas_dia IS 'Horas pagadas de cada chófer y día según Asistencias de Odoo (día de la entrada, hora de Madrid). Una asistencia abierta cuenta hasta ahora.';

CREATE VIEW calculo.horas_pagadas_semana AS
SELECT conductor_id,
       date_trunc('week', fecha)::date AS semana,
       sum(horas) AS horas,
       count(*) AS dias,
       greatest(sum(horas) - (sistema.parametro('jornada.horas_semana', date_trunc('week', fecha)::date))::numeric, 0) AS horas_extra
FROM calculo.horas_pagadas_dia
GROUP BY 1, 2;
COMMENT ON VIEW calculo.horas_pagadas_semana IS 'Horas de cada chófer por semana (de lunes a domingo) y las que pasan de la jornada ordinaria (jornada.horas_semana).';

CREATE VIEW calculo.horas_pagadas_resumen AS
WITH hoy AS (
  SELECT (now() AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::date AS d
)
SELECT c.id AS conductor_id,
       coalesce(sum(h.horas) FILTER (WHERE h.fecha = hoy.d), 0) AS horas_hoy,
       coalesce(sum(h.horas) FILTER (WHERE h.fecha >= date_trunc('week', hoy.d)::date), 0) AS horas_semana,
       coalesce(sum(h.horas) FILTER (WHERE h.fecha >= date_trunc('month', hoy.d)::date), 0) AS horas_mes,
       count(h.fecha) FILTER (WHERE h.fecha >= date_trunc('month', hoy.d)::date) AS dias_mes,
       coalesce((SELECT s.horas_extra FROM calculo.horas_pagadas_semana s
                 WHERE s.conductor_id = c.id AND s.semana = date_trunc('week', hoy.d)::date), 0) AS horas_extra_semana,
       coalesce((SELECT sum(s.horas_extra) FROM calculo.horas_pagadas_semana s
                 WHERE s.conductor_id = c.id AND s.semana >= date_trunc('month', hoy.d)::date AND s.semana <= hoy.d), 0) AS horas_extra_mes
FROM nucleo.conductores c
CROSS JOIN hoy
LEFT JOIN calculo.horas_pagadas_dia h
  ON h.conductor_id = c.id
 AND h.fecha >= least(date_trunc('week', hoy.d), date_trunc('month', hoy.d))::date
WHERE c.fecha_baja IS NULL
GROUP BY c.id, hoy.d;
COMMENT ON VIEW calculo.horas_pagadas_resumen IS 'Lo que enseña la vista «Conductores» del panel hasta la fase 5: horas pagadas de hoy, de la semana y del mes de cada chófer, y horas extra. Las extra del mes son las de las semanas que empiezan en ese mes.';

CREATE VIEW calculo.saldo_vacaciones AS
SELECT s.conductor_id,
       s.anio,
       s.generados_dias,
       s.disfrutados_dias,
       coalesce(p.pedidos_dias, 0) AS pedidos_dias,
       s.generados_dias - s.disfrutados_dias - coalesce(p.pedidos_dias, 0) AS disponibles_dias,
       s.al_final_del_anio_dias,
       s.sincronizado_en
FROM nucleo.saldos_vacaciones s
LEFT JOIN (
  SELECT a.conductor_id,
         extract(year FROM a.desde)::smallint AS anio,
         sum(a.dias) AS pedidos_dias
  FROM nucleo.ausencias a
  JOIN nucleo.tipos_ausencia t ON t.codigo = a.tipo
  WHERE a.estado = 'pedida' AND t.descuenta_vacaciones
  GROUP BY 1, 2
) p ON p.conductor_id = s.conductor_id AND p.anio = s.anio;
COMMENT ON VIEW calculo.saldo_vacaciones IS 'Lo que ve el chófer en «Mis vacaciones»: generados − disfrutados − pedidos sin resolver = disponibles. Lo pedido descuenta ya, para no pedir dos veces los mismos días.';

CREATE VIEW calculo.ausencias_por_dia AS
SELECT d.fecha,
       count(*) FILTER (WHERE a.estado = 'aprobada') AS fuera,
       count(*) FILTER (WHERE a.estado = 'pedida') AS pedidas,
       array_agg(a.conductor_id ORDER BY a.conductor_id) FILTER (WHERE a.estado = 'aprobada') AS conductores_fuera,
       (sistema.parametro('vacaciones.max_fuera', d.fecha))::int AS max_fuera,
       count(*) > (sistema.parametro('vacaciones.max_fuera', d.fecha))::int AS supera_maximo
FROM nucleo.ausencias a
CROSS JOIN LATERAL (
  SELECT g::date AS fecha FROM generate_series(a.desde, a.hasta, interval '1 day') g
) d
WHERE a.estado IN ('pedida', 'aprobada')
GROUP BY d.fecha;
COMMENT ON VIEW calculo.ausencias_por_dia IS 'Cuántos chóferes están fuera cada día (aprobadas) y cuántos lo han pedido. Pinta el calendario del panel y avisa si, aprobando lo pedido, se pasa de vacaciones.max_fuera.';
