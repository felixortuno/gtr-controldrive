CREATE TABLE nucleo.ausencias (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id      bigint NOT NULL REFERENCES nucleo.conductores,
  tipo              text NOT NULL REFERENCES nucleo.tipos_ausencia,
  desde             date NOT NULL,
  hasta             date NOT NULL,
  dias              numeric(5,1) NOT NULL CHECK (dias > 0),
  motivo            text,
  estado            text NOT NULL DEFAULT 'pedida' CHECK (estado IN ('pedida', 'aprobada', 'rechazada', 'anulada')),
  origen            text NOT NULL CHECK (origen IN ('app', 'odoo')),
  pedida_en         timestamptz NOT NULL DEFAULT now(),
  resuelta_por      bigint REFERENCES nucleo.usuarios,
  resuelta_en       timestamptz,
  respuesta         text,
  odoo_ausencia_id  integer UNIQUE,
  lote_id           bigint REFERENCES ingesta.lotes,
  actualizado_en    timestamptz NOT NULL DEFAULT now(),
  CHECK (hasta >= desde),
  CHECK (estado IN ('pedida', 'anulada') OR resuelta_en IS NOT NULL),
  CHECK (estado <> 'rechazada' OR origen = 'odoo' OR respuesta IS NOT NULL),
  CONSTRAINT ausencias_sin_solape EXCLUDE USING gist (conductor_id WITH =, daterange(desde, hasta, '[]') WITH &&) WHERE (estado IN ('pedida', 'aprobada'))
);
CREATE INDEX ausencias_conductor ON nucleo.ausencias (conductor_id, desde);
CREATE INDEX ausencias_por_resolver ON nucleo.ausencias (pedida_en) WHERE estado = 'pedida';
CREATE TRIGGER ausencias_actualizado BEFORE UPDATE ON nucleo.ausencias FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.ausencias IS 'Vacaciones y permisos: los que pide el chófer desde el móvil y los que ya están en Ausencias de Odoo. Al aprobar o rechazar en el panel, se escribe en Odoo y se avisa al chófer.';
COMMENT ON COLUMN nucleo.ausencias.dias IS 'Días que descuenta, como los cuenta Odoo según el tipo (naturales o laborables). El móvil los enseña antes de pedir.';
COMMENT ON COLUMN nucleo.ausencias.respuesta IS 'Por qué se rechaza, en una frase. Obligatoria al rechazar desde el panel: el chófer la ve.';
COMMENT ON CONSTRAINT ausencias_sin_solape ON nucleo.ausencias IS 'No se pueden pedir dos veces los mismos días: las pedidas y aprobadas de un chófer no se pisan.';

CREATE TABLE nucleo.saldos_vacaciones (
