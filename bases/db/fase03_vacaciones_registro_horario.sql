COMMENT ON TABLE nucleo.saldos_vacaciones IS 'Copia del saldo de vacaciones que calcula Odoo con su plan de acumulación. Aquí no se calcula: si no cuadra, se corrige en Odoo y se vuelve a sincronizar.';
