-- =====================================================================
-- FASE 4 · REPOSTAJE CON EL EXCEL DE SOLRED
-- ---------------------------------------------------------------------
-- El control de repostaje por matrícula, solo con los Excel que ya da
-- Solred: el informe mensual «Vehículos», el detalle con fecha y hora y
-- el listado de estaciones con descuento. No necesita Movildata: el
-- conductor de cada repostaje se deduce en la fase 8.
-- Las redes y las tarjetas son tablas desde el primer día: la segunda
-- red (Moeve) será un INSERT, no un cambio de estructura.
-- Depende de: fase 0 (lotes, vehículos) y fase 2 (notificaciones).
-- =====================================================================

INSERT INTO sistema.funciones (codigo, nombre, fase, descripcion) VALUES
  ('repostaje',          'Control de repostaje',  4, 'Informe mensual de Solred por matrícula: % en la óptima y ahorro perdido.'),
  ('avisos_correccion',  'Avisos de corrección',  4, 'Aviso con el dato concreto a quien reposta peor, revisado por tráfico.');

CREATE TABLE nucleo.redes (
  codigo   text PRIMARY KEY,
  nombre   text NOT NULL,
  activa   boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE nucleo.redes IS 'Redes de gasóleo con tarjeta de empresa. Hoy Solred; la segunda (p. ej. Moeve) se activa en la fase 10.';

INSERT INTO nucleo.redes (codigo, nombre, activa) VALUES
  ('solred', 'Solred', true),
  ('moeve',  'Moeve',  false);

CREATE TABLE nucleo.tarjetas_combustible (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  red             text NOT NULL REFERENCES nucleo.redes,
  identificador   text NOT NULL,
  vehiculo_id     bigint REFERENCES nucleo.vehiculos,
  activa          boolean NOT NULL DEFAULT true,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (red, identificador)
);
COMMENT ON TABLE nucleo.tarjetas_combustible IS 'Tarjetas de gasóleo. Van con el camión, no con la persona.';
COMMENT ON COLUMN nucleo.tarjetas_combustible.identificador IS 'Como aparece en los informes de la red (normalmente enmascarado). Nunca el número completo ni el PIN.';

CREATE TABLE nucleo.gasolineras (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  red               text NOT NULL REFERENCES nucleo.redes,
  codigo_red        text NOT NULL,
  nombre            text NOT NULL,
  direccion         text,
  municipio         text,
  provincia         text,
  lat               numeric(9,6) NOT NULL,
  lon               numeric(9,6) NOT NULL,
  descuento_eur_l   numeric(5,3),
  acceso_pesados    boolean,
  tiene_adblue      boolean,
  horario           text,
  id_ministerio     text,
  servicios         jsonb,
  activa            boolean NOT NULL DEFAULT true,
  lote_id           bigint REFERENCES ingesta.lotes,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (red, codigo_red),
  CHECK (lat BETWEEN 27 AND 44.5 AND lon BETWEEN -18.5 AND 4.5)
);
CREATE INDEX gasolineras_posicion ON nucleo.gasolineras (lat, lon) WHERE activa;
CREATE TRIGGER gasolineras_actualizado BEFORE UPDATE ON nucleo.gasolineras FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.gasolineras IS 'Estaciones de nuestras redes (2.425 de Solred con descuento). Son las únicas que ve el chófer en el mapa.';
COMMENT ON COLUMN nucleo.gasolineras.codigo_red IS 'Código de la estación en el listado de la red.';
COMMENT ON COLUMN nucleo.gasolineras.descuento_eur_l IS 'Descuento pactado en €/L (0,220 en 1.631 estaciones de Solred).';
COMMENT ON COLUMN nucleo.gasolineras.lat IS 'El CHECK de lat/lon cubre España peninsular, Baleares, Canarias y Portugal: si alguien las intercambia, la fila no entra.';
COMMENT ON COLUMN nucleo.gasolineras.id_ministerio IS 'Id en el geoportal de gasolineras del Ministerio: precio de surtidor de respaldo.';

CREATE TABLE nucleo.informes_red_mes (
  id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  red                        text NOT NULL REFERENCES nucleo.redes,
  mes                        date NOT NULL CHECK (extract(day FROM mes) = 1),
  vehiculo_id                bigint NOT NULL REFERENCES nucleo.vehiculos,
  tarjeta_id                 bigint REFERENCES nucleo.tarjetas_combustible,
  importe_eur                numeric(10,2),
  litros                     numeric(10,2),
  n_repostajes               integer,
  pct_optimo                 numeric(5,2) CHECK (pct_optimo BETWEEN 0 AND 100),
  descuento_eur              numeric(10,2),
  ahorro_perdido_eur         numeric(10,2),
  estacion_mas_perdida_id    bigint REFERENCES nucleo.gasolineras,
  alternativa_id             bigint REFERENCES nucleo.gasolineras,
  alternativa_precio_eur_l   numeric(6,3),
  alternativa_desvio_min     numeric(5,1),
  lote_id                    bigint NOT NULL REFERENCES ingesta.lotes,
  n_fila                     integer,
  UNIQUE (red, mes, vehiculo_id)
);
COMMENT ON TABLE nucleo.informes_red_mes IS 'Informe mensual «Vehículos» de la red: una fila por matrícula y mes, tal como lo calcula Solred.';
COMMENT ON COLUMN nucleo.informes_red_mes.mes IS 'Primer día del mes: 2026-09-01 = septiembre de 2026.';
COMMENT ON COLUMN nucleo.informes_red_mes.pct_optimo IS '«%Opt.» de Solred: porcentaje de repostajes hechos en la gasolinera óptima.';
COMMENT ON COLUMN nucleo.informes_red_mes.n_fila IS 'Junto con lote_id lleva a la fila original del Excel (ingesta.filas).';

CREATE TABLE nucleo.repostajes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  red             text NOT NULL REFERENCES nucleo.redes,
  tarjeta_id      bigint REFERENCES nucleo.tarjetas_combustible,
  vehiculo_id     bigint NOT NULL REFERENCES nucleo.vehiculos,
  fecha_hora      timestamptz NOT NULL,
  gasolinera_id   bigint REFERENCES nucleo.gasolineras,
  producto        text,
  litros          numeric(8,2) NOT NULL CHECK (litros > 0),
  precio_eur_l    numeric(6,3),
  importe_eur     numeric(10,2),
  descuento_eur   numeric(8,2),
  lote_id         bigint NOT NULL REFERENCES ingesta.lotes,
  n_fila          integer,
  CONSTRAINT repostajes_sin_duplicados UNIQUE (red, vehiculo_id, fecha_hora, litros)
);
CREATE INDEX repostajes_vehiculo_fecha ON nucleo.repostajes (vehiculo_id, fecha_hora);
COMMENT ON TABLE nucleo.repostajes IS 'Cada repostaje facturado por la red, del Excel de detalle con fecha y hora. El conductor no se guarda: se deduce (calculo.repostajes_atribuidos, fase 8).';
COMMENT ON CONSTRAINT repostajes_sin_duplicados ON nucleo.repostajes IS 'Reimportar el mismo Excel no duplica repostajes.';

CREATE TABLE nucleo.avisos_correccion (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id          bigint NOT NULL REFERENCES nucleo.vehiculos,
  conductor_id         bigint REFERENCES nucleo.conductores,
  mes                  date NOT NULL CHECK (extract(day FROM mes) = 1),
  motivo               text NOT NULL,
  mensaje              text NOT NULL,
  dato                 jsonb,
  estado               text NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador', 'revisado', 'enviado', 'descartado')),
  revisado_por         bigint REFERENCES nucleo.usuarios,
  enviado_en           timestamptz,
  notificacion_id      bigint REFERENCES sistema.notificaciones,
  pct_optimo_antes     numeric(5,2),
  pct_optimo_despues   numeric(5,2),
  creado_en            timestamptz NOT NULL DEFAULT now(),
  CHECK (estado NOT IN ('revisado', 'enviado') OR revisado_por IS NOT NULL)
);
COMMENT ON TABLE nucleo.avisos_correccion IS 'Aviso a quien reposta fuera de la óptima, con su dato concreto. Tráfico lo revisa antes de enviarlo. Hasta la fase 8 va por matrícula; después, al conductor.';
COMMENT ON COLUMN nucleo.avisos_correccion.dato IS 'Lo que justifica el aviso: {"cts_l_de_mas": 6.1, "coste_eur": 212.40, "pct_optimo": 41}.';
COMMENT ON COLUMN nucleo.avisos_correccion.pct_optimo_despues IS 'Se rellena con el informe del mes siguiente: ¿ha mejorado tras el aviso? Cierra el ciclo.';

CREATE VIEW calculo.perdida_repostaje_mes AS
SELECT i.mes,
       i.red,
       v.matricula,
       i.vehiculo_id,
       i.n_repostajes,
       i.litros,
       i.importe_eur,
       i.pct_optimo,
       i.ahorro_perdido_eur,
       round(100 * i.ahorro_perdido_eur / nullif(i.litros, 0), 1) AS cts_l_perdidos,
       rank() OVER (PARTITION BY i.mes, i.red ORDER BY i.ahorro_perdido_eur DESC NULLS LAST) AS puesto,
       round(100 * sum(i.ahorro_perdido_eur) OVER (PARTITION BY i.mes, i.red ORDER BY i.ahorro_perdido_eur DESC NULLS LAST
                                                   ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
                 / nullif(sum(i.ahorro_perdido_eur) OVER (PARTITION BY i.mes, i.red), 0), 1) AS pct_acumulado
FROM nucleo.informes_red_mes i
JOIN nucleo.vehiculos v ON v.id = i.vehiculo_id;
COMMENT ON VIEW calculo.perdida_repostaje_mes IS 'Panel de repostaje: qué matrículas pierden más cada mes y qué parte del total acumulan («las 10 que más pierden suman el 57 %»).';
