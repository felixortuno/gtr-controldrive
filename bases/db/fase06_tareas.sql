-- =====================================================================
-- FASE 6 · TAREAS
-- ---------------------------------------------------------------------
-- Tráfico manda cada servicio al móvil del chófer como una tarea con sus
-- etapas (salida, en carga, cargado, en descarga, descargado). El chófer
-- las marca con un toque y registra los problemas con foto. Las tareas
-- son las de Odoo (Proyecto): se leen de allí y lo que hace el chófer se
-- escribe allí. Desde la tarea se abre DECA si al cargar cambió algo.
-- Depende de: fase 1 (DECA, Odoo), fase 2 (avisos) y fase 5 (camión de
-- cada chófer).
-- =====================================================================

INSERT INTO sistema.funciones (codigo, nombre, fase, descripcion) VALUES
  ('tareas', 'Tareas', 6, 'Servicios enviados al chófer con sus etapas, problemas con foto y acceso a DECA desde la tarea.');


-- Tipos y tareas -----------------------------------------------------------

CREATE TABLE nucleo.tipos_tarea (
  codigo            text PRIMARY KEY,
  nombre            text NOT NULL,
  etapas            text[] NOT NULL CHECK (cardinality(etapas) BETWEEN 1 AND 12),
  odoo_proyecto_id  integer,
  activo            boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE nucleo.tipos_tarea IS 'Cada tipo de servicio y sus etapas, en orden. Al crear una tarea se copian sus etapas; cambiar la plantilla no toca las tareas ya creadas.';
COMMENT ON COLUMN nucleo.tipos_tarea.odoo_proyecto_id IS 'Proyecto de Odoo del que salen las tareas de este tipo.';

INSERT INTO nucleo.tipos_tarea (codigo, nombre, etapas) VALUES
  ('carga_descarga', 'Carga y descarga', '{"Salida hacia carga","En carga","Cargado","En descarga","Descargado"}');

CREATE TABLE nucleo.tareas (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  odoo_tarea_id   integer UNIQUE,
  tipo            text NOT NULL REFERENCES nucleo.tipos_tarea,
  conductor_id    bigint NOT NULL REFERENCES nucleo.conductores,
  vehiculo_id     bigint REFERENCES nucleo.vehiculos,
  empresa         text REFERENCES nucleo.empresas,
  titulo          text NOT NULL,
  pedido          text,
  lugar_carga     text,
  lugar_descarga  text,
  cita_carga      timestamptz,
  cita_descarga   timestamptz,
  notas           text,
  estado          text NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'en_curso', 'hecha', 'anulada')),
  origen          text NOT NULL CHECK (origen IN ('odoo', 'panel')),
  creada_por      bigint REFERENCES nucleo.usuarios,
  creada_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  lote_id         bigint REFERENCES ingesta.lotes,
  CHECK (origen <> 'panel' OR creada_por IS NOT NULL),
  CHECK (pedido IS NULL OR empresa IS NOT NULL)
);
CREATE INDEX tareas_conductor ON nucleo.tareas (conductor_id, cita_carga);
CREATE INDEX tareas_abiertas ON nucleo.tareas (estado) WHERE estado IN ('pendiente', 'en_curso');
CREATE TRIGGER tareas_actualizado BEFORE UPDATE ON nucleo.tareas FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.tareas IS 'Servicios que tráfico manda al chófer. Vienen de Odoo (Proyecto) o se crean en el panel y se escriben en Odoo. Solo se copian las que tienen chófer.';
COMMENT ON COLUMN nucleo.tareas.odoo_tarea_id IS 'Id de la tarea en Odoo. Es el mismo que guarda DECA en nucleo.deca_correcciones.tarea_odoo_id: así se ve qué correcciones se hicieron en cada tarea.';
COMMENT ON COLUMN nucleo.tareas.vehiculo_id IS 'El camión con el que se hace. Si tráfico no lo indica, se pone el de la franja del chófer al empezar la primera etapa.';
COMMENT ON COLUMN nucleo.tareas.pedido IS 'Nº de la orden de transporte (p. ej. S2630118). Con él, el botón «Corregir orden» abre DECA ya buscada.';
COMMENT ON COLUMN nucleo.tareas.estado IS 'en_curso al marcar la primera etapa y hecha al marcar la última. anulada solo desde Odoo o el panel.';

CREATE TABLE nucleo.tareas_etapas (
  tarea_id         bigint NOT NULL REFERENCES nucleo.tareas,
  n                smallint NOT NULL CHECK (n >= 1),
  nombre           text NOT NULL,
  hecha_en         timestamptz,
  origen           text CHECK (origen IN ('app', 'panel', 'automatica')),
  lat              numeric(9,6),
  lon              numeric(9,6),
  copiada_odoo_en  timestamptz,
  PRIMARY KEY (tarea_id, n),
  CHECK ((hecha_en IS NULL) = (origen IS NULL))
);
COMMENT ON TABLE nucleo.tareas_etapas IS 'Las etapas de cada tarea, copiadas de su tipo al crearla. El chófer las marca con un toque y se copian a Odoo.';
COMMENT ON COLUMN nucleo.tareas_etapas.origen IS 'app (el chófer), panel (tráfico la marca por él) o automatica (más adelante, al llegar el camión a la dirección según Movildata).';
COMMENT ON COLUMN nucleo.tareas_etapas.lat IS 'Dónde estaba el camión al marcarla, según Movildata (no el móvil).';

CREATE TABLE nucleo.tareas_problemas (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarea_id         bigint NOT NULL REFERENCES nucleo.tareas,
  conductor_id     bigint NOT NULL REFERENCES nucleo.conductores,
  tipo             text NOT NULL CHECK (tipo IN ('retraso', 'averia', 'mercancia', 'cliente', 'accidente', 'documentacion', 'otro')),
  texto            text,
  foto_id          bigint REFERENCES nucleo.archivos,
  ocurrido_en      timestamptz NOT NULL DEFAULT now(),
  resuelto_por     bigint REFERENCES nucleo.usuarios,
  resuelto_en      timestamptz,
  solucion         text,
  odoo_mensaje_id  integer UNIQUE,
  CHECK (tipo <> 'otro' OR texto IS NOT NULL),
  CHECK ((resuelto_en IS NULL) = (resuelto_por IS NULL))
);
CREATE INDEX tareas_problemas_abiertos ON nucleo.tareas_problemas (ocurrido_en) WHERE resuelto_en IS NULL;
COMMENT ON TABLE nucleo.tareas_problemas IS 'Problemas que registra el chófer en una tarea, con foto. Avisan a tráfico al momento y se copian al chat de la tarea en Odoo.';
COMMENT ON COLUMN nucleo.tareas_problemas.tipo IS 'retraso, avería, mercancía (dañada o distinta), cliente (cerrado, no recibe), accidente, documentación u otro (con texto).';
COMMENT ON COLUMN nucleo.tareas_problemas.odoo_mensaje_id IS 'Mensaje del chat de la tarea en Odoo donde se copió, con la foto adjunta.';


-- Lo que se deduce ---------------------------------------------------------

CREATE VIEW calculo.tareas_avance AS
SELECT t.id AS tarea_id,
       t.conductor_id,
       t.vehiculo_id,
       t.titulo,
       t.pedido,
       t.estado,
       t.cita_carga,
       t.cita_descarga,
       count(e.n) AS etapas,
       count(e.hecha_en) AS etapas_hechas,
       (array_agg(e.nombre ORDER BY e.n DESC) FILTER (WHERE e.hecha_en IS NOT NULL))[1] AS ultima_etapa,
       max(e.hecha_en) AS ultima_etapa_en,
       (array_agg(e.nombre ORDER BY e.n) FILTER (WHERE e.hecha_en IS NULL))[1] AS siguiente_etapa,
       (SELECT count(*) FROM nucleo.tareas_problemas p WHERE p.tarea_id = t.id AND p.resuelto_en IS NULL) AS problemas_abiertos,
       (SELECT count(*) FROM nucleo.deca_correcciones d WHERE d.tarea_odoo_id = t.odoo_tarea_id AND d.resultado = 'guardada') AS correcciones_deca
FROM nucleo.tareas t
LEFT JOIN nucleo.tareas_etapas e ON e.tarea_id = t.id
GROUP BY t.id;
COMMENT ON VIEW calculo.tareas_avance IS 'Cómo va cada tarea: etapas hechas de cuántas, la última y la siguiente, problemas sin resolver y correcciones DECA hechas desde ella. Es la lista de «Tareas» del panel.';

CREATE VIEW calculo.tareas_mes AS
SELECT x.conductor_id,
       x.mes,
       count(*) FILTER (WHERE x.estado <> 'anulada') AS asignadas,
       count(*) FILTER (WHERE x.estado = 'hecha') AS hechas,
       count(*) FILTER (WHERE x.con_problema) AS con_problemas
FROM (
  SELECT t.conductor_id,
         t.estado,
         date_trunc('month', coalesce(t.cita_carga, t.creada_en) AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::date AS mes,
         EXISTS (SELECT 1 FROM nucleo.tareas_problemas p WHERE p.tarea_id = t.id) AS con_problema
  FROM nucleo.tareas t
) x
GROUP BY 1, 2;
COMMENT ON VIEW calculo.tareas_mes IS 'Tareas de cada chófer por mes: asignadas, hechas y con algún problema. Sale en la vista «Conductores» del panel.';
