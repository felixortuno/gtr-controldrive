CREATE VIEW calculo.anexo_ii AS
SELECT p.vehiculo_id,
       v.matricula,
       date_trunc('month', p.fecha)::date AS mes,
       p.fecha,
       us.nombre AS chofer,
       p.lugar,
       (p.empieza_en AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::time AS empieza,
       (p.termina_en AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::time AS termina,
       p.servicios,
       p.km_fin AS kilometraje,
       p.recorrido_km,
       (SELECT sum(t.litros)
          FROM nucleo.tickets t
         WHERE t.vehiculo_id = p.vehiculo_id
           AND t.conductor_id = p.conductor_id
           AND t.estado = 'confirmado'
           AND (t.fecha_hora AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::date = p.fecha) AS gasoil_litros,
       r.matricula AS remolque,
       CASE WHEN p.taller THEN concat_ws(' · ', p.taller_motivo, 'Orden ' || p.taller_n_orden) END AS observaciones,
       p.estado
FROM nucleo.partes_dia p
JOIN nucleo.vehiculos v ON v.id = p.vehiculo_id
JOIN nucleo.conductores c ON c.id = p.conductor_id
JOIN nucleo.usuarios us ON us.id = c.usuario_id
LEFT JOIN nucleo.remolques r ON r.id = p.remolque_id;
COMMENT ON VIEW calculo.anexo_ii IS 'Las filas del Anexo II con las columnas del papel. El gas-oil, en litros y sumando los tickets confirmados del día.';

CREATE VIEW calculo.consumo_entre_llenados AS
WITH llenos AS (
  SELECT t.vehiculo_id, t.id, t.fecha_hora, t.km_odometro,
         lag(t.fecha_hora)  OVER w AS fecha_anterior,
         lag(t.km_odometro) OVER w AS km_anterior
  FROM nucleo.tickets t
  WHERE t.lleno AND t.estado = 'confirmado' AND t.km_odometro IS NOT NULL
  WINDOW w AS (PARTITION BY t.vehiculo_id ORDER BY t.fecha_hora)
)
SELECT l.vehiculo_id,
       l.fecha_anterior AS desde,
       l.fecha_hora AS hasta,
       l.km_odometro - l.km_anterior AS recorrido_km,
       s.litros,
       round(100 * s.litros / nullif(l.km_odometro - l.km_anterior, 0), 1) AS consumo_l_100km
FROM llenos l
CROSS JOIN LATERAL (
  SELECT sum(t2.litros) AS litros
  FROM nucleo.tickets t2
  WHERE t2.vehiculo_id = l.vehiculo_id
    AND t2.estado = 'confirmado'
    AND t2.fecha_hora > l.fecha_anterior
    AND t2.fecha_hora <= l.fecha_hora
) s
WHERE l.fecha_anterior IS NOT NULL;
COMMENT ON VIEW calculo.consumo_entre_llenados IS 'Consumo real: litros cargados entre dos llenados completos ÷ km recorridos. El dato que hoy no sale del parte en papel.';

CREATE VIEW calculo.incidencias_tickets AS
SELECT 'ticket_sin_repostaje' AS tipo, t.id AS ticket_id, NULL::bigint AS repostaje_id, t.vehiculo_id, t.fecha_hora,
       'Ticket sin repostaje en Solred' AS texto
FROM nucleo.tickets t
WHERE t.estado = 'confirmado' AND t.repostaje_id IS NULL
  AND EXISTS (SELECT 1 FROM nucleo.repostajes r WHERE r.vehiculo_id = t.vehiculo_id AND r.fecha_hora > t.fecha_hora)
UNION ALL
SELECT 'repostaje_sin_ticket', NULL, r.id, r.vehiculo_id, r.fecha_hora,
       'Repostaje en Solred sin ticket: recordar al chófer la foto'
FROM nucleo.repostajes r
WHERE NOT EXISTS (SELECT 1 FROM nucleo.tickets t WHERE t.repostaje_id = r.id AND t.estado <> 'anulado')
UNION ALL
SELECT 'litros_no_cuadran', t.id, r.id, t.vehiculo_id, t.fecha_hora,
       format('Ticket %s L, Solred %s L', t.litros, r.litros)
FROM nucleo.tickets t
JOIN nucleo.repostajes r ON r.id = t.repostaje_id
WHERE abs(t.litros - r.litros) > r.litros * (sistema.parametro('tickets.cruce_litros_pct'))::numeric / 100
UNION ALL
SELECT 'lejos_del_camion', NULL, r.id, r.vehiculo_id, r.fecha_hora,
       format('Repostaje a %s km de donde estaba el camión', calculo.distancia_km(g.lat, g.lon, p.lat, p.lon))
FROM nucleo.repostajes r
JOIN nucleo.gasolineras g ON g.id = r.gasolinera_id
CROSS JOIN LATERAL (
  SELECT tl.lat, tl.lon
  FROM nucleo.telemetria tl
  WHERE tl.vehiculo_id = r.vehiculo_id
    AND tl.ts BETWEEN r.fecha_hora - interval '30 minutes' AND r.fecha_hora + interval '30 minutes'
  ORDER BY abs(extract(epoch FROM tl.ts - r.fecha_hora))
  LIMIT 1
) p
WHERE calculo.distancia_km(g.lat, g.lon, p.lat, p.lon) > (sistema.parametro('tickets.lejos_km'))::numeric;
COMMENT ON VIEW calculo.incidencias_tickets IS 'Lo que no cuadra entre tickets y Solred, sin tener que buscarlo: ticket sin repostaje, repostaje sin ticket, litros distintos y repostaje lejos del camión.';
