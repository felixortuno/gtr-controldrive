CREATE TABLE nucleo.servicios (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id    bigint NOT NULL REFERENCES nucleo.conductores,
  vehiculo_id     bigint NOT NULL REFERENCES nucleo.vehiculos,
  ocurrido_en     timestamptz NOT NULL DEFAULT now(),
  lat             numeric(9,6),
  lon             numeric(9,6),
  origen          text NOT NULL DEFAULT 'app' CHECK (origen IN ('app', 'odoo')),
  referencia_odoo text,
  anulado_en      timestamptz
);
CREATE INDEX servicios_conductor ON nucleo.servicios (conductor_id, ocurrido_en);
COMMENT ON TABLE nucleo.servicios IS 'Cada viaje terminado, con un toque. Guardar el momento (y no solo un contador) permite comprobarlo y, más adelante, traerlo de Odoo.';

CREATE TABLE nucleo.tickets (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id    bigint NOT NULL REFERENCES nucleo.conductores,
  vehiculo_id     bigint NOT NULL REFERENCES nucleo.vehiculos,
  foto_id         bigint NOT NULL REFERENCES nucleo.archivos,
  fecha_hora      timestamptz,
  estacion_texto  text,
  gasolinera_id   bigint REFERENCES nucleo.gasolineras,
  litros          numeric(8,2),
  precio_eur_l    numeric(6,3),
  importe_eur     numeric(10,2),
  lleno           boolean NOT NULL DEFAULT false,
  km_odometro     numeric(10,1),
  lectura_ia      jsonb,
  cuadra          boolean GENERATED ALWAYS AS (abs(litros * precio_eur_l - importe_eur) <= 0.05) STORED,
  estado          text NOT NULL DEFAULT 'leyendo' CHECK (estado IN ('leyendo', 'por_confirmar', 'repetir_foto', 'confirmado', 'anulado')),
  repostaje_id    bigint REFERENCES nucleo.repostajes,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  CHECK (estado <> 'confirmado' OR (litros > 0 AND precio_eur_l > 0 AND importe_eur > 0 AND fecha_hora IS NOT NULL))
);
CREATE UNIQUE INDEX tickets_un_repostaje ON nucleo.tickets (repostaje_id) WHERE repostaje_id IS NOT NULL AND estado <> 'anulado';
CREATE INDEX tickets_vehiculo_fecha ON nucleo.tickets (vehiculo_id, fecha_hora);
CREATE TRIGGER tickets_actualizado BEFORE UPDATE ON nucleo.tickets FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.tickets IS 'Foto del ticket de repostaje y lo que se leyó de ella. Cada dato por separado y con su unidad: nadie teclea un número suelto.';
COMMENT ON COLUMN nucleo.tickets.lectura_ia IS 'Respuesta del modelo de visión tal cual, para revisar si algo se leyó mal.';
COMMENT ON COLUMN nucleo.tickets.cuadra IS 'Calculada por la base de datos: litros × €/L = importe (±0,05 €). Si no cuadra, la app pide repetir la foto.';
COMMENT ON COLUMN nucleo.tickets.lleno IS '«¿Depósito lleno?» con un toque. Dos llenados seguidos dan el consumo real.';
COMMENT ON COLUMN nucleo.tickets.repostaje_id IS 'Su repostaje en el detalle de Solred, cuando se encuentra. Un repostaje solo puede tener un ticket.';

CREATE TABLE nucleo.partes_dia (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id     bigint NOT NULL REFERENCES nucleo.vehiculos,
  fecha           date NOT NULL,
  conductor_id    bigint NOT NULL REFERENCES nucleo.conductores,
  lugar           text,
  empieza_en      timestamptz,
  termina_en      timestamptz,
  km_inicio       numeric(10,1),
  km_fin          numeric(10,1),
  recorrido_km    numeric(10,1) GENERATED ALWAYS AS (km_fin - km_inicio) STORED,
  servicios       smallint CHECK (servicios >= 0),
  remolque_id     bigint REFERENCES nucleo.remolques,
  taller          boolean NOT NULL DEFAULT false,
  taller_motivo   text,
  taller_n_orden  text,
  taller_foto_id  bigint REFERENCES nucleo.archivos,
  estado          text NOT NULL DEFAULT 'abierto' CHECK (estado IN ('abierto', 'confirmado', 'sin_confirmar', 'validado')),
  confirmado_en   timestamptz,
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (vehiculo_id, fecha, conductor_id),
  CHECK (km_fin IS NULL OR km_inicio IS NULL OR km_fin >= km_inicio),
  CHECK (termina_en IS NULL OR empieza_en IS NULL OR termina_en >= empieza_en),
  CHECK (NOT taller OR taller_motivo IS NOT NULL)
);
CREATE TRIGGER partes_dia_actualizado BEFORE UPDATE ON nucleo.partes_dia FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.partes_dia IS 'Una fila del Anexo II: un camión, un día, un conductor. Horas y km vienen puestos; el chófer confirma servicios, lugar, remolque y taller.';
COMMENT ON COLUMN nucleo.partes_dia.recorrido_km IS 'Lo calcula la base de datos: km_fin − km_inicio. La columna que en papel nadie rellenaba.';
COMMENT ON COLUMN nucleo.partes_dia.estado IS 'sin_confirmar = el chófer no cerró la jornada; se rellenó con Movildata y queda para tráfico.';

CREATE TABLE nucleo.partes_mes (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehiculo_id        bigint NOT NULL REFERENCES nucleo.vehiculos,
  mes                date NOT NULL CHECK (extract(day FROM mes) = 1),
  validado_por       bigint REFERENCES nucleo.usuarios,
  validado_en        timestamptz,
  exportado_id       bigint REFERENCES nucleo.archivos,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (vehiculo_id, mes)
);
COMMENT ON TABLE nucleo.partes_mes IS 'La hoja del Anexo II de un camión y un mes. Pendiente: confirmar si hay una hoja por turno (mañanas / tardes).';

CREATE TABLE nucleo.firmas_parte (
  parte_mes_id   bigint NOT NULL REFERENCES nucleo.partes_mes,
  conductor_id   bigint NOT NULL REFERENCES nucleo.conductores,
  firma_id       bigint NOT NULL REFERENCES nucleo.archivos,
