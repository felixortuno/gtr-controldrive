CREATE TABLE nucleo.validaciones_adr (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gasolinera_id  bigint NOT NULL REFERENCES nucleo.gasolineras,
  estado         text NOT NULL CHECK (estado IN ('compatible', 'confirmar', 'descartada', 'pendiente')),
  motivo         text NOT NULL,
  fuentes        jsonb NOT NULL DEFAULT '[]',
  origen         text NOT NULL CHECK (origen IN ('agente', 'usuario')),
  revisado_por   bigint REFERENCES nucleo.usuarios,
  revisado_en    timestamptz NOT NULL DEFAULT now(),
  lote_id        bigint REFERENCES ingesta.lotes,
  CHECK (origen <> 'usuario' OR revisado_por IS NOT NULL)
);
CREATE INDEX validaciones_adr_gasolinera ON nucleo.validaciones_adr (gasolinera_id, revisado_en DESC);
COMMENT ON TABLE nucleo.validaciones_adr IS 'Historial de revisiones ADR de cada estación. Nunca se pisa: el estado actual es la última revisión (calculo.estado_adr).';
COMMENT ON COLUMN nucleo.validaciones_adr.fuentes IS 'Qué se consultó y qué dijo cada fuente: RIMP, túneles, altura de marquesina, OSM, llamada de tráfico…';
COMMENT ON COLUMN nucleo.validaciones_adr.revisado_por IS 'Quién confirmó (tráfico o el consejero de seguridad). Vacío si lo revisó el agente.';

CREATE TABLE nucleo.incidencias_gasolinera (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gasolinera_id  bigint NOT NULL REFERENCES nucleo.gasolineras,
  conductor_id   bigint NOT NULL REFERENCES nucleo.conductores,
  ocurrida_en    timestamptz NOT NULL DEFAULT now(),
  tipo           text NOT NULL CHECK (tipo IN ('no_admite_adr', 'sin_acceso_pesados', 'cerrada', 'precio_distinto', 'otra')),
  texto          text,
  foto_id        bigint REFERENCES nucleo.archivos,
  estado         text NOT NULL DEFAULT 'abierta' CHECK (estado IN ('abierta', 'revisada', 'descartada')),
  revisada_por   bigint REFERENCES nucleo.usuarios,
  revisada_en    timestamptz
);
COMMENT ON TABLE nucleo.incidencias_gasolinera IS 'Lo que reportan los chóferes desde la gasolinera. Tráfico la revisa y, si procede, crea una validación nueva.';

CREATE VIEW calculo.estado_adr AS
SELECT g.id AS gasolinera_id,
       g.red,
       g.nombre,
       coalesce(v.estado, 'pendiente') AS estado,
       v.motivo,
       v.origen,
       v.revisado_en,
       (SELECT count(*) FROM nucleo.incidencias_gasolinera i WHERE i.gasolinera_id = g.id AND i.estado = 'abierta') AS incidencias_abiertas
FROM nucleo.gasolineras g
LEFT JOIN LATERAL (
  SELECT x.estado, x.motivo, x.origen, x.revisado_en
  FROM nucleo.validaciones_adr x
  WHERE x.gasolinera_id = g.id
  ORDER BY x.revisado_en DESC, x.id DESC
  LIMIT 1
) v ON true
WHERE g.activa;
COMMENT ON VIEW calculo.estado_adr IS 'Semáforo ADR actual de cada estación. Sin revisión = pendiente: solo «compatible» se recomienda sin aviso.';

CREATE FUNCTION nucleo.puede_cargar_adr(p_conductor_id bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1
    FROM nucleo.documentos d
    WHERE d.conductor_id = p_conductor_id
      AND d.tipo = 'carne_adr'
      AND d.estado = 'vigente'
      AND d.caduca_el >= current_date
  )
$$;
COMMENT ON FUNCTION nucleo.puede_cargar_adr(bigint) IS 'Con el carné ADR caducado (o sin carné) no se puede marcar «Carga ADR».';

