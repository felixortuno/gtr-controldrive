-- DECA (corregir la orden de transporte en Odoo) ya funciona: se integra
-- tal cual, pero ahora cada corrección lleva el conductor que la hizo
-- (su PIN sustituye al código compartido). Y «Mis notas», que es la
-- función más sencilla de la app.
-- Depende de: fase 0.
-- =====================================================================

INSERT INTO sistema.funciones (codigo, nombre, fase, descripcion) VALUES
  ('deca',  'Corregir orden de transporte', 1, 'Flujo DECA contra Odoo, con el PIN de cada conductor.'),
  ('notas', 'Mis notas',                    1, 'Notas privadas del conductor, con texto o foto.');

CREATE TABLE nucleo.deca_correcciones (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id   bigint NOT NULL REFERENCES nucleo.conductores,
  empresa        text NOT NULL REFERENCES nucleo.empresas,
  pedido         text NOT NULL,
  tarea_odoo_id  integer,
  antes          jsonb NOT NULL,
  despues        jsonb NOT NULL,
  resultado      text NOT NULL CHECK (resultado IN ('guardada', 'sin_cambios', 'simulada', 'error')),
  error          text,
  pdf_id         bigint REFERENCES nucleo.archivos,
  ocurrido_en    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX deca_correcciones_conductor ON nucleo.deca_correcciones (conductor_id, ocurrido_en DESC);
CREATE INDEX deca_correcciones_pedido ON nucleo.deca_correcciones (pedido);
COMMENT ON TABLE nucleo.deca_correcciones IS 'Registro propio de cada corrección hecha con DECA. Odoo sigue siendo la fuente de la orden; esto dice quién cambió qué y cuándo.';
COMMENT ON COLUMN nucleo.deca_correcciones.pedido IS 'Nº de pedido de Odoo, p. ej. S2621473.';
COMMENT ON COLUMN nucleo.deca_correcciones.antes IS 'Mercancía, bultos, euro palets y peso antes del cambio.';
COMMENT ON COLUMN nucleo.deca_correcciones.resultado IS 'simulada = DRY_RUN (no se escribió en Odoo).';

CREATE TABLE nucleo.notas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id  bigint NOT NULL REFERENCES nucleo.conductores,
  texto         text,
  foto_id       bigint REFERENCES nucleo.archivos,
  creada_en     timestamptz NOT NULL DEFAULT now(),
  editada_en    timestamptz,
  borrada_en    timestamptz,
  CHECK (texto IS NOT NULL OR foto_id IS NOT NULL)
);
CREATE INDEX notas_conductor ON nucleo.notas (conductor_id, creada_en DESC) WHERE borrada_en IS NULL;
COMMENT ON TABLE nucleo.notas IS 'Notas privadas del conductor. Solo las ve él: ni administración puede leerlas (regla de la API, con test).';
