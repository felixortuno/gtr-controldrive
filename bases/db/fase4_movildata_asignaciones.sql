CREATE TABLE nucleo.telemetria (
  vehiculo_id        bigint NOT NULL REFERENCES nucleo.vehiculos,
  ts                 timestamptz NOT NULL,
  lat                numeric(9,6),
  lon                numeric(9,6),
  velocidad_kmh      numeric(5,1),
  rumbo_grados       smallint,
  km_odometro        numeric(10,1),
  motor_encendido    boolean,
  tarjeta_tacografo  text,
  lote_id            bigint REFERENCES ingesta.lotes,
  PRIMARY KEY (vehiculo_id, ts)
);
CREATE INDEX telemetria_ts ON nucleo.telemetria USING brin (ts);
COMMENT ON TABLE nucleo.telemetria IS 'Serie temporal por camión, ya normalizada (el JSON original queda en ingesta.respuestas_api). Unas 50.000–100.000 filas al día: índice BRIN por fecha y, si pasa de 50 millones, particiones por mes.';
COMMENT ON COLUMN nucleo.telemetria.km_odometro IS 'Odómetro del camión. Los km de un tramo = máximo − mínimo dentro de la franja.';
COMMENT ON COLUMN nucleo.telemetria.tarjeta_tacografo IS 'Tarjeta insertada en ese momento. Qué endpoint de Movildata la da se confirma en el descubrimiento (semana 1).';

CREATE TABLE nucleo.actividad_tacografo (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarjeta_tacografo  text NOT NULL,
  conductor_id       bigint REFERENCES nucleo.conductores,
  vehiculo_id        bigint REFERENCES nucleo.vehiculos,
  actividad          text NOT NULL CHECK (actividad IN ('conduccion', 'descanso', 'disponibilidad', 'otro_trabajo', 'desconocida')),
  inicio             timestamptz NOT NULL,
  fin                timestamptz,
  lote_id            bigint REFERENCES ingesta.lotes,
  UNIQUE (tarjeta_tacografo, inicio, actividad),
  CHECK (fin IS NULL OR fin >= inicio)
);
CREATE INDEX actividad_conductor ON nucleo.actividad_tacografo (conductor_id, inicio);
COMMENT ON TABLE nucleo.actividad_tacografo IS 'Actividad de la tarjeta del tacógrafo: las horas y pausas oficiales, las mismas que vería un inspector.';
COMMENT ON COLUMN nucleo.actividad_tacografo.conductor_id IS 'Vacío si la tarjeta todavía no está dada de alta: tráfico lo ve como tarjeta desconocida.';

CREATE TABLE nucleo.asignaciones (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id       bigint NOT NULL REFERENCES nucleo.conductores,
  vehiculo_id        bigint NOT NULL REFERENCES nucleo.vehiculos,
  inicio             timestamptz NOT NULL,
  fin                timestamptz,
  origen             text NOT NULL CHECK (origen IN ('tacografo', 'app', 'qr', 'admin', 'cierre_auto')),
  confirmada_en      timestamptz,
  remolque_id        bigint REFERENCES nucleo.remolques,
  carga_adr          boolean NOT NULL DEFAULT false,
  numeros_onu        text[],
  corregida_por      bigint REFERENCES nucleo.usuarios,
  motivo_correccion  text,
  creado_en          timestamptz NOT NULL DEFAULT now(),
  actualizado_en     timestamptz NOT NULL DEFAULT now(),
  CHECK (fin IS NULL OR fin > inicio),
  CHECK (origen <> 'admin' OR (corregida_por IS NOT NULL AND motivo_correccion IS NOT NULL)),
  CHECK (carga_adr OR numeros_onu IS NULL),
  CONSTRAINT asignaciones_sin_solape_conductor EXCLUDE USING gist (conductor_id WITH =, tstzrange(inicio, fin) WITH &&)
);
CREATE UNIQUE INDEX asignaciones_una_abierta ON nucleo.asignaciones (conductor_id) WHERE fin IS NULL;
CREATE INDEX asignaciones_vehiculo ON nucleo.asignaciones (vehiculo_id, inicio);
CREATE TRIGGER asignaciones_actualizado BEFORE UPDATE ON nucleo.asignaciones FOR EACH ROW EXECUTE FUNCTION sistema.tocar_actualizado_en();
COMMENT ON TABLE nucleo.asignaciones IS 'Franjas conductor ↔ camión: quién llevaba cada camión y entre qué horas. Es la llave de toda la atribución.';
COMMENT ON COLUMN nucleo.asignaciones.fin IS 'Vacío = sigue abierta. Un conductor solo puede tener una abierta.';
COMMENT ON COLUMN nucleo.asignaciones.origen IS 'De dónde salió la franja: tacografo (automática), app (elegida a mano), qr, admin (corrección) o cierre_auto.';
COMMENT ON COLUMN nucleo.asignaciones.confirmada_en IS 'Cuándo confirmó el chófer con un toque el camión detectado.';
COMMENT ON COLUMN nucleo.asignaciones.numeros_onu IS 'Nº ONU de la mercancía peligrosa que lleva, si marca «Carga ADR».';
COMMENT ON CONSTRAINT asignaciones_sin_solape_conductor ON nucleo.asignaciones IS 'Un conductor no puede estar en dos camiones a la vez: la base de datos rechaza franjas que se pisan.';

CREATE FUNCTION nucleo.abrir_asignacion(
  p_conductor_id bigint,
  p_vehiculo_id  bigint,
  p_inicio       timestamptz,
  p_origen       text,
  p_usuario_id   bigint DEFAULT NULL,
  p_motivo       text DEFAULT NULL
) RETURNS bigint
LANGUAGE plpgsql AS $$
DECLARE
  v_abierta nucleo.asignaciones%ROWTYPE;
  v_id      bigint;
BEGIN
  SELECT * INTO v_abierta
  FROM nucleo.asignaciones
  WHERE conductor_id = p_conductor_id AND fin IS NULL
  FOR UPDATE;

  IF FOUND AND v_abierta.vehiculo_id = p_vehiculo_id THEN
    RETURN v_abierta.id;
  END IF;

  IF FOUND THEN
    UPDATE nucleo.asignaciones SET fin = p_inicio WHERE id = v_abierta.id;
  END IF;

  INSERT INTO nucleo.asignaciones (conductor_id, vehiculo_id, inicio, origen, corregida_por, motivo_correccion)
  VALUES (p_conductor_id, p_vehiculo_id, p_inicio, p_origen, p_usuario_id, p_motivo)
  RETURNING id INTO v_id;

  RETURN v_id;
END $$;
COMMENT ON FUNCTION nucleo.abrir_asignacion(bigint, bigint, timestamptz, text, bigint, text) IS 'Cambio de camión en una sola transacción: cierra la franja abierta del conductor y abre la nueva. Si ya está en ese camión, no hace nada.';


-- Lo que se deduce -------------------------------------------------------

CREATE VIEW calculo.telemetria_conductor AS
SELECT a.conductor_id,
       a.id AS asignacion_id,
       t.vehiculo_id,
       t.ts,
       t.lat,
       t.lon,
       t.velocidad_kmh,
       t.km_odometro,
       t.motor_encendido
FROM nucleo.asignaciones a
JOIN nucleo.telemetria t
  ON t.vehiculo_id = a.vehiculo_id
 AND t.ts >= a.inicio
 AND t.ts < coalesce(a.fin, 'infinity');
COMMENT ON VIEW calculo.telemetria_conductor IS 'LA REGLA DE ATRIBUCIÓN: los datos de un conductor son los de cada camión dentro de SU franja. Filtrar siempre por conductor_id y fechas.';

CREATE VIEW calculo.km_asignacion AS
SELECT a.id AS asignacion_id,
       a.conductor_id,
       a.vehiculo_id,
       a.inicio,
       a.fin,
       min(t.km_odometro) AS km_inicio,
       max(t.km_odometro) AS km_fin,
       max(t.km_odometro) - min(t.km_odometro) AS recorrido_km
FROM nucleo.asignaciones a
LEFT JOIN nucleo.telemetria t
  ON t.vehiculo_id = a.vehiculo_id
 AND t.ts >= a.inicio
 AND t.ts < coalesce(a.fin, 'infinity')
GROUP BY a.id;
COMMENT ON VIEW calculo.km_asignacion IS 'Km de cada franja según el odómetro de Movildata.';

CREATE VIEW calculo.horas_dia AS
SELECT x.conductor_id,
       (x.inicio AT TIME ZONE (sistema.parametro('zona_horaria') #>> '{}'))::date AS fecha,
       round(sum(x.segundos) FILTER (WHERE x.actividad = 'conduccion')     / 3600, 2) AS horas_conduccion,
       round(sum(x.segundos) FILTER (WHERE x.actividad = 'descanso')       / 3600, 2) AS horas_descanso,
       round(sum(x.segundos) FILTER (WHERE x.actividad = 'disponibilidad') / 3600, 2) AS horas_disponibilidad,
       round(sum(x.segundos) FILTER (WHERE x.actividad = 'otro_trabajo')   / 3600, 2) AS horas_otro_trabajo
FROM (
  SELECT conductor_id, actividad, inicio,
         extract(epoch FROM coalesce(fin, now()) - inicio) AS segundos
  FROM nucleo.actividad_tacografo
  WHERE conductor_id IS NOT NULL
) x
GROUP BY 1, 2;
COMMENT ON VIEW calculo.horas_dia IS 'Horas de conducción, descanso, disponibilidad y otros trabajos de cada conductor y día (hora de Madrid), según su tarjeta.';

CREATE VIEW calculo.estado_flota AS
SELECT v.id AS vehiculo_id,
       v.matricula,
       u.ts AS ultimo_dato_en,
       round(extract(epoch FROM now() - u.ts) / 60) AS minutos_desde_dato,
       u.lat,
       u.lon,
       u.velocidad_kmh,
       u.motor_encendido,
       coalesce(u.velocidad_kmh > (sistema.parametro('alertas.en_marcha_kmh'))::numeric, false) AS en_marcha,
       a.conductor_id,
       us.nombre AS conductor,
       a.inicio AS asignado_desde,
       a.origen AS origen_asignacion
FROM nucleo.vehiculos v
LEFT JOIN LATERAL (
  SELECT t.ts, t.lat, t.lon, t.velocidad_kmh, t.motor_encendido
  FROM nucleo.telemetria t
  WHERE t.vehiculo_id = v.id
  ORDER BY t.ts DESC
  LIMIT 1
) u ON true
LEFT JOIN LATERAL (
  SELECT x.conductor_id, x.inicio, x.origen
  FROM nucleo.asignaciones x
  WHERE x.vehiculo_id = v.id AND x.fin IS NULL
  ORDER BY x.inicio DESC
  LIMIT 1
) a ON true
LEFT JOIN nucleo.conductores c ON c.id = a.conductor_id
LEFT JOIN nucleo.usuarios us ON us.id = c.usuario_id
WHERE v.activo;
COMMENT ON VIEW calculo.estado_flota IS 'Foto de la flota ahora: última posición de cada camión, si está en marcha y quién lo lleva.';

CREATE VIEW calculo.alertas AS
SELECT 'en_marcha_sin_conductor' AS tipo,
       'alta' AS gravedad,
       e.vehiculo_id,
       NULL::bigint AS conductor_id,
       e.ultimo_dato_en AS desde,
       format('%s circula sin tarjeta ni asignación', e.matricula) AS texto
FROM calculo.estado_flota e
WHERE e.en_marcha
  AND e.conductor_id IS NULL
  AND e.minutos_desde_dato <= (sistema.parametro('alertas.datos_atrasados_min'))::int
UNION ALL
SELECT 'solape',
       'media',
       a1.vehiculo_id,
       a1.conductor_id,
       greatest(a1.inicio, a2.inicio),
       format('%s: dos conductores a la vez (revisar; puede ser doble tripulación)', v.matricula)
FROM nucleo.asignaciones a1
JOIN nucleo.asignaciones a2
  ON a2.vehiculo_id = a1.vehiculo_id
 AND a2.id > a1.id
 AND tstzrange(a1.inicio, a1.fin) && tstzrange(a2.inicio, a2.fin)
JOIN nucleo.vehiculos v ON v.id = a1.vehiculo_id
WHERE coalesce(a1.fin, now()) > now() - interval '7 days'
UNION ALL
SELECT 'sincronizacion_atrasada',
       'alta',
       NULL,
       NULL,
       max(l.importado_en),
       format('Movildata sin datos nuevos desde hace %s min', round(extract(epoch FROM now() - max(l.importado_en)) / 60))
FROM ingesta.lotes l
WHERE l.origen = 'movildata' AND l.estado = 'importado'
HAVING max(l.importado_en) < now() - make_interval(mins => (sistema.parametro('alertas.datos_atrasados_min'))::int);
COMMENT ON VIEW calculo.alertas IS 'Alertas para tráfico, calculadas al momento: camión en marcha sin conductor, dos conductores en el mismo camión y Movildata atrasado.';

CREATE VIEW calculo.frescura_datos AS
SELECT origen,
       max(importado_en) AS ultimo_dato_en,
       round(extract(epoch FROM now() - max(importado_en)) / 60) AS minutos
FROM ingesta.lotes
WHERE estado = 'importado'
GROUP BY origen;
COMMENT ON VIEW calculo.frescura_datos IS 'Para mostrar «actualizado hace X min» en lugar de fallar cuando Movildata tarda.';
