CREATE TABLE ingesta.correos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id    text NOT NULL UNIQUE,
  buzon         text NOT NULL,
  remitente     text NOT NULL,
  asunto        text,
  recibido_en   timestamptz NOT NULL,
  cuerpo_texto  text,
  adjuntos      bigint[],
  red           text REFERENCES nucleo.redes,
  estado        text NOT NULL DEFAULT 'nuevo' CHECK (estado IN ('nuevo', 'procesado', 'no_reconocido', 'error')),
  lote_id       bigint REFERENCES ingesta.lotes,
  error         text
