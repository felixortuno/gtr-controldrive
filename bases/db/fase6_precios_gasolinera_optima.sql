-- Lo que se deduce -------------------------------------------------------

CREATE FUNCTION calculo.precios_del_dia(p_fecha date DEFAULT current_date)
RETURNS TABLE (gasolinera_id bigint, red text, precio_eur_l numeric, origen_precio text)
LANGUAGE sql STABLE AS $$
  SELECT g.id,
         g.red,
         coalesce(pe.precio_eur_l, pp.precio_eur_l, pr.precio_eur_l,
                  round(m.precio_gasoleo_a_eur_l - coalesce(g.descuento_eur_l, 0)
                        - coalesce((sistema.parametro('gasoleo.ayuda_eur_l', p_fecha))::numeric, 0), 3)),
         CASE
           WHEN pe.precio_eur_l IS NOT NULL THEN 'correo_estacion'
           WHEN pp.precio_eur_l IS NOT NULL THEN 'correo_provincia'
           WHEN pr.precio_eur_l IS NOT NULL THEN 'correo_red'
           WHEN m.precio_gasoleo_a_eur_l IS NOT NULL THEN 'respaldo_ministerio'
         END
  FROM nucleo.gasolineras g
  JOIN nucleo.redes rd ON rd.codigo = g.red AND rd.activa
  LEFT JOIN nucleo.precios_dia pe ON pe.fecha = p_fecha AND pe.red = g.red AND pe.ambito = 'estacion'  AND pe.gasolinera_id = g.id
  LEFT JOIN nucleo.precios_dia pp ON pp.fecha = p_fecha AND pp.red = g.red AND pp.ambito = 'provincia' AND pp.provincia = g.provincia
  LEFT JOIN nucleo.precios_dia pr ON pr.fecha = p_fecha AND pr.red = g.red AND pr.ambito = 'red'
  LEFT JOIN LATERAL (
    SELECT x.precio_gasoleo_a_eur_l
    FROM nucleo.precios_ministerio x
    WHERE x.id_ministerio = g.id_ministerio AND x.fecha BETWEEN p_fecha - 3 AND p_fecha
    ORDER BY x.fecha DESC
    LIMIT 1
  ) m ON true
  WHERE g.activa
$$;
COMMENT ON FUNCTION calculo.precios_del_dia(date) IS 'Precio de cada gasolinera en una fecha y de dónde sale: correo (estación > provincia > red) o, si no llegó, respaldo = Ministerio − descuento − ayuda.';

CREATE VIEW calculo.repostajes_atribuidos AS
SELECT r.id AS repostaje_id,
       r.red,
       r.vehiculo_id,
       r.fecha_hora,
       r.gasolinera_id,
       r.litros,
       r.precio_eur_l,
       r.importe_eur,
       a.conductor_id,
       coalesce(a.origen, 'sin_asignar') AS atribucion
FROM nucleo.repostajes r
LEFT JOIN nucleo.asignaciones a
  ON a.vehiculo_id = r.vehiculo_id
 AND r.fecha_hora >= a.inicio
 AND r.fecha_hora < coalesce(a.fin, 'infinity');
COMMENT ON VIEW calculo.repostajes_atribuidos IS 'Quién repostó: la tarjeta va con el camión, así que cada repostaje se cruza con la franja del conductor. Si se corrige una asignación, la atribución cambia sola.';
