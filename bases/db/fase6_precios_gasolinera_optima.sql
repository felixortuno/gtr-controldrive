COMMENT ON TABLE ingesta.correos IS 'Correos de precios tal como llegan al buzón. El message_id impide leer dos veces el mismo.';
COMMENT ON COLUMN ingesta.correos.adjuntos IS 'Ids de nucleo.archivos (el Excel o PDF adjunto).';

CREATE TABLE nucleo.precios_dia (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha          date NOT NULL,
  red            text NOT NULL REFERENCES nucleo.redes,
  ambito         text NOT NULL CHECK (ambito IN ('estacion', 'provincia', 'red')),
  gasolinera_id  bigint REFERENCES nucleo.gasolineras,
  provincia      text,
  precio_eur_l   numeric(6,3) NOT NULL CHECK (precio_eur_l BETWEEN 0.5 AND 3),
  origen         text NOT NULL CHECK (origen IN ('correo', 'manual')),
  lote_id        bigint REFERENCES ingesta.lotes,
  cargado_por    bigint REFERENCES nucleo.usuarios,
  cargado_en     timestamptz NOT NULL DEFAULT now(),
  CHECK ((ambito = 'estacion')  = (gasolinera_id IS NOT NULL)),
  CHECK ((ambito = 'provincia') = (provincia IS NOT NULL)),
  CHECK (origen <> 'manual' OR cargado_por IS NOT NULL)
);
CREATE UNIQUE INDEX precios_dia_unico ON nucleo.precios_dia (fecha, red, ambito, coalesce(gasolinera_id, 0), coalesce(provincia, ''));
COMMENT ON TABLE nucleo.precios_dia IS 'Precio pactado del gasóleo profesional de cada día. Admite precio por estación, por provincia o uno para toda la red, porque aún no se sabe cómo viene el correo.';
COMMENT ON COLUMN nucleo.precios_dia.ambito IS 'A qué se aplica: una estación, una provincia o toda la red. Gana el más concreto.';
COMMENT ON COLUMN nucleo.precios_dia.precio_eur_l IS 'Pendiente: confirmar si el precio del correo ya descuenta la ayuda al gasóleo profesional; si no, hay que restarla para compararlo con el respaldo.';

