CREATE TABLE nucleo.premios (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre         text NOT NULL,
  descripcion    text,
  coste_monedas  integer NOT NULL CHECK (coste_monedas > 0),
  foto_id        bigint REFERENCES nucleo.archivos,
  stock          integer CHECK (stock >= 0),
  activo         boolean NOT NULL DEFAULT true,
  creado_en      timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE nucleo.premios IS 'Catálogo de premios. Lo decide la empresa; antes de abrirlo, confirmar con la asesoría cómo tributan.';
COMMENT ON COLUMN nucleo.premios.stock IS 'Vacío = sin límite.';

CREATE TABLE nucleo.canjes (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id    bigint NOT NULL REFERENCES nucleo.conductores,
  premio_id       bigint NOT NULL REFERENCES nucleo.premios,
  coste_monedas   integer NOT NULL CHECK (coste_monedas > 0),
  estado          text NOT NULL DEFAULT 'pedido' CHECK (estado IN ('pedido', 'aprobado', 'rechazado', 'entregado', 'cancelado')),
  pedido_en       timestamptz NOT NULL DEFAULT now(),
  resuelto_por    bigint REFERENCES nucleo.usuarios,
  resuelto_en     timestamptz,
  motivo_rechazo  text,
  entregado_en    timestamptz,
  CHECK (estado IN ('pedido', 'cancelado') OR resuelto_por IS NOT NULL),
  CHECK (estado <> 'rechazado' OR motivo_rechazo IS NOT NULL)
);
COMMENT ON TABLE nucleo.canjes IS 'El chófer pide un premio y la oficina lo aprueba. Las monedas se descuentan al aprobar; mientras tanto quedan reservadas.';
COMMENT ON COLUMN nucleo.canjes.coste_monedas IS 'Lo que costaba al pedirlo, aunque el catálogo cambie después.';

CREATE TABLE nucleo.monedas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id  bigint NOT NULL REFERENCES nucleo.conductores,
  ocurrido_en   timestamptz NOT NULL DEFAULT now(),
  tipo          text NOT NULL CHECK (tipo IN ('tramo_semana', 'hito_racha', 'canje', 'caducidad', 'ajuste')),
  cantidad      integer NOT NULL CHECK (cantidad <> 0),
  semana        date CHECK (extract(isodow FROM semana) = 1),
  canje_id      bigint REFERENCES nucleo.canjes,
  caduca_el     date,
  motivo        text NOT NULL,
  creado_por    bigint REFERENCES nucleo.usuarios,
  CHECK (
       (tipo IN ('tramo_semana', 'hito_racha') AND cantidad > 0 AND semana IS NOT NULL AND caduca_el IS NOT NULL)
    OR (tipo = 'canje'     AND cantidad < 0 AND canje_id IS NOT NULL)
    OR (tipo = 'caducidad' AND cantidad < 0)
    OR (tipo = 'ajuste'    AND creado_por IS NOT NULL)),
  CONSTRAINT monedas_una_vez_por_semana UNIQUE (conductor_id, semana, tipo)
);
CREATE UNIQUE INDEX monedas_un_cargo_por_canje ON nucleo.monedas (canje_id) WHERE canje_id IS NOT NULL;
COMMENT ON TABLE nucleo.monedas IS 'Libro de movimientos de Monedas Trimodos: lo que se gana suma, lo que se canjea o caduca resta. El saldo es la suma; nada se sobrescribe.';
COMMENT ON COLUMN nucleo.monedas.motivo IS 'En palabras del chófer: «Semana del 5 de octubre: nota 8,6».';
COMMENT ON CONSTRAINT monedas_una_vez_por_semana ON nucleo.monedas IS 'Si la tarea de los lunes corre dos veces, no paga dos veces.';

CREATE VIEW calculo.saldo_monedas AS
SELECT c.id AS conductor_id,
       coalesce(m.saldo, 0) AS saldo,
       coalesce(r.reservadas, 0) AS reservadas,
       coalesce(m.saldo, 0) - coalesce(r.reservadas, 0) AS disponibles,
       coalesce(m.caducan_30_dias, 0) AS caducan_30_dias
FROM nucleo.conductores c
LEFT JOIN (
  SELECT conductor_id,
         sum(cantidad) AS saldo,
         sum(cantidad) FILTER (WHERE cantidad > 0 AND caduca_el BETWEEN current_date AND current_date + 30) AS caducan_30_dias
  FROM nucleo.monedas
  GROUP BY conductor_id
) m ON m.conductor_id = c.id
LEFT JOIN (
  SELECT conductor_id, sum(coste_monedas) AS reservadas
  FROM nucleo.canjes
  WHERE estado = 'pedido'
  GROUP BY conductor_id
) r ON r.conductor_id = c.id;
COMMENT ON VIEW calculo.saldo_monedas IS 'Saldo de cada chófer, monedas reservadas en canjes pendientes y cuántas ganadas caducan en 30 días (para avisarle antes).';
