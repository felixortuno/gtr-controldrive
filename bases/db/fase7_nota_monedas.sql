CREATE TABLE nucleo.eventos_conduccion (
  vehiculo_id   bigint NOT NULL REFERENCES nucleo.vehiculos,
  ocurrido_en   timestamptz NOT NULL,
  tipo          text NOT NULL CHECK (tipo IN ('aceleracion_brusca', 'frenada_brusca', 'exceso_velocidad', 'ralenti')),
  duracion_s    integer,
  valor         numeric,
  lote_id       bigint REFERENCES ingesta.lotes,
  PRIMARY KEY (vehiculo_id, ocurrido_en, tipo)
);
COMMENT ON TABLE nucleo.eventos_conduccion IS 'Eventos de conducción de Movildata. Se atribuyen al conductor con su franja, igual que la telemetría.';
COMMENT ON COLUMN nucleo.eventos_conduccion.valor IS 'Lo que mida el evento: km/h por encima del límite, fuerza de la frenada…';

CREATE TABLE nucleo.objetivos_nota (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  componente     text NOT NULL CHECK (componente IN ('aceleraciones_frenadas', 'ralenti', 'velocidad', 'consumo', 'repostaje', 'tiempos_pausas')),
  valor_diez     numeric NOT NULL,
  valor_cero     numeric NOT NULL,
  unidad         text NOT NULL,
  vigente_desde  date NOT NULL,
  fijado_por     bigint REFERENCES nucleo.usuarios,
  UNIQUE (componente, vigente_desde)
);
COMMENT ON TABLE nucleo.objetivos_nota IS 'Qué es un 10 y qué es un 0 en cada parte de la nota. Lo fija tráfico; vacía hasta entonces. Cambiar un objetivo no reescribe las notas pasadas.';
COMMENT ON COLUMN nucleo.objetivos_nota.valor_diez IS 'Medida con la que se saca un 10, p. ej. 0,5 eventos cada 100 km. Entre valor_diez y valor_cero la nota es proporcional.';

CREATE TABLE calculo.notas_semana (
  conductor_id   bigint NOT NULL REFERENCES nucleo.conductores,
  semana         date NOT NULL CHECK (extract(isodow FROM semana) = 1),
  componente     text NOT NULL CHECK (componente IN ('aceleraciones_frenadas', 'ralenti', 'velocidad', 'consumo', 'repostaje', 'tiempos_pausas')),
  valor_medido   numeric,
  unidad         text,
  nota           numeric(3,1) NOT NULL CHECK (nota BETWEEN 0 AND 10),
  detalle        jsonb,
  calculado_en   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conductor_id, semana, componente)
);
COMMENT ON TABLE calculo.notas_semana IS 'Nota de cada parte, por conductor y semana. La calcula la tarea de los lunes y se guarda tal cual, para que la nota de una semana no cambie después.';
COMMENT ON COLUMN calculo.notas_semana.semana IS 'Lunes de la semana.';
COMMENT ON COLUMN calculo.notas_semana.detalle IS 'De dónde sale el número, para enseñárselo al chófer: eventos, km, objetivos usados…';

CREATE TABLE calculo.semanas_conductor (
  conductor_id         bigint NOT NULL REFERENCES nucleo.conductores,
  semana               date NOT NULL CHECK (extract(isodow FROM semana) = 1),
  jornadas             smallint NOT NULL,
  infracciones_tiempos smallint NOT NULL DEFAULT 0,
  calculado_en         timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conductor_id, semana)
);
COMMENT ON TABLE calculo.semanas_conductor IS 'Resumen semanal que decide si hay monedas: jornadas trabajadas y pausas saltadas o excesos de horas.';

CREATE VIEW calculo.nota_semana AS
SELECT n.conductor_id,
       n.semana,
       round(avg(n.nota), 1) AS nota,
       count(*) AS partes,
       count(*) = 6 AS completa,
       round(avg(n.nota) - lag(avg(n.nota)) OVER (PARTITION BY n.conductor_id ORDER BY n.semana), 1) AS cambio,
       (array_agg(n.componente ORDER BY n.nota ASC))[1] AS lo_que_mas_baja
FROM calculo.notas_semana n
GROUP BY n.conductor_id, n.semana;
COMMENT ON VIEW calculo.nota_semana IS 'Una sola nota para el chófer: media simple de sus partes, el cambio respecto a la semana anterior y lo que más le baja.';


